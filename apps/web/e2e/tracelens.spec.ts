import { test, expect, type Page } from '@playwright/test'

async function login(page: Page, actor = 'investigator') {
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await page.getByRole('combobox', { name: 'Tài khoản', exact: true }).selectOption(actor)
  await page.getByRole('button', { name: 'Vào không gian điều tra →' }).click()
  await expect(page.locator('.case-header')).toContainText(actor === 'other-investigator' ? 'TL-1043' : 'TL-1041')
}

test('two contrasting cases: real worker, cited source, human review, audit and export', async ({ page }) => {
  const browserErrors: string[] = []
  page.on('pageerror', error => browserErrors.push(error.message))
  await login(page)
  await expect(page.locator('.case-header')).toContainText('6 redemption')
  await page.locator('.case-item').filter({ hasText: 'TL-1042' }).click()
  await expect(page.locator('.case-header')).toContainText('6 redemption')
  await page.locator('.modebar').getByRole('button', { name: 'Bắt đầu điều tra →' }).click()
  await expect(page.locator('.recommendation')).toContainText('Đề xuất không hành động', { timeout: 30000 })
  await page.locator('.case-item').filter({ hasText: 'TL-1041' }).click()
  await page.locator('.modebar').getByRole('button', { name: 'Bắt đầu điều tra →' }).click()
  await expect(page.locator('.recommendation')).toContainText('Đề xuất chuyển kiểm tra thêm', { timeout: 30000 })
  await page.locator('.citation').filter({ hasText: 'Bằng chứng' }).first().click()
  await expect(page.locator('dialog')).toBeVisible()
  await page.locator('dialog .source').first().click()
  await expect(page.locator('dialog')).toContainText('snapshot_id')
  await page.getByRole('button', { name: 'Đóng nguồn' }).click()
  await page.getByRole('button', { name: 'Đăng xuất' }).click()
  await login(page, 'reviewer')
  await page.locator('.tabs button').filter({ hasText: 'Người duyệt' }).click()
  await page.locator('.review select').selectOption('ESCALATE_FOR_MANUAL_REVIEW')
  await page.locator('.review textarea').fill('Đã đối chiếu lịch sử, khoảng thiết bị và sổ voucher; chuyển kiểm tra thủ công.')
  await page.getByRole('button', { name: 'Ghi quyết định sandbox' }).click()
  await expect(page.locator('.review')).toContainText('Chuyển điều tra thủ công')
  await page.locator('.tabs button').filter({ hasText: 'Audit & lượt chạy' }).click()
  await expect(page.locator('.audit')).toContainText('review.recorded')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Export JSON' }).click()
  const downloaded = await downloadPromise
  expect(downloaded.suggestedFilename()).toBe('TL-1041.json')
  const exported = await page.request.get('/api/cases/TL-1041/export')
  const data = await exported.json()
  expect(data.decisions).toHaveLength(1)
  expect(data.evidence.length).toBeGreaterThan(0)
  await page.screenshot({ path: 'test-results/desktop-audit.png', fullPage: true })
  expect(browserErrors).toEqual([])
})

test('mobile layout and tenant isolation use the real API', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await login(page, 'other-investigator')
  const denied = await page.request.get('/api/cases/TL-1041/export')
  expect(denied.status()).toBe(404)
  await expect(page.locator('.case-header')).toContainText('TL-1043')
  const overflowing = await page.evaluate(() => Array.from(document.querySelectorAll('body *'))
    .filter(el => el.getBoundingClientRect().right > window.innerWidth && getComputedStyle(el).position !== 'fixed')
    .map(el => ({ tag: el.tagName, className: el.className, right: el.getBoundingClientRect().right })))
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), JSON.stringify(overflowing)).toBe(true)
  await page.screenshot({ path: 'test-results/mobile-case.png', fullPage: true })
})
